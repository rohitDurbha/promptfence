#!/usr/bin/env python3
"""Export the rule set to JSON so a browser can run the same checks.

Python stays the single source of truth. The static demo loads this file
rather than carrying its own copy of the patterns, and `--check` fails if the
committed JSON has drifted from the Python rules, so CI catches divergence.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "src"))

from promptfence import __version__  # noqa: E402
from promptfence.patterns import INPUT_RULES, OUTPUT_RULES  # noqa: E402

OUT_PATH = Path(__file__).resolve().parent.parent / "web" / "rules.json"


def build() -> dict[str, object]:
    def serialize(rules: tuple, boundary: str) -> list[dict[str, str]]:
        return [
            {
                "rule_id": r.rule_id,
                "name": r.name,
                "boundary": boundary,
                "severity": r.severity.value,
                "pattern": r.pattern.pattern,
                "description": r.description,
            }
            for r in rules
        ]

    return {
        "version": __version__,
        "note": (
            "Generated by scripts/export_rules.py from src/promptfence/patterns.py. "
            "Do not edit by hand."
        ),
        "flags": "i",
        "rules": serialize(INPUT_RULES, "input") + serialize(OUTPUT_RULES, "output"),
    }


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit non-zero if the committed file differs from the Python rules",
    )
    args = parser.parse_args(argv)

    payload = json.dumps(build(), indent=2) + "\n"

    if args.check:
        if not OUT_PATH.exists():
            print(f"FAIL: {OUT_PATH} is missing; run scripts/export_rules.py", file=sys.stderr)
            return 1
        if OUT_PATH.read_text() != payload:
            print(
                f"FAIL: {OUT_PATH.name} is stale. The Python rules changed without "
                "regenerating it; run scripts/export_rules.py",
                file=sys.stderr,
            )
            return 1
        print(f"{OUT_PATH.name} is up to date")
        return 0

    OUT_PATH.parent.mkdir(parents=True, exist_ok=True)
    OUT_PATH.write_text(payload)
    print(f"wrote {OUT_PATH} ({len(build()['rules'])} rules)")  # type: ignore[arg-type]
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
